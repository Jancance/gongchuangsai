function validate_source_ruler_20261111
% 纸外独立尺段检查，旧模型不使用本次尺段拟合。
root=fileparts(fileparts(mfilename('fullpath')));
out=fullfile(root,'evidence','integration','2026-11-11','source-view-entry','ruler-review');
d=jsondecode(fileread(fullfile(out,'measurement-input.json')));
models=jsondecode(fileread(fullfile(root,'evidence','integration','2026-11-11','source-view-entry','paper50-geometry','model-comparison.json')));
allPoints=reshape([d.ticks.point_px],2,[])';allTruth=[d.ticks.position_mm]';
accepted=~[d.ticks.search_boundary_hit]';
points=allPoints(accepted,:);truth=allTruth(accepted);
checks=struct('name',{},'passed',{});
check('actual single frame1920x1080',d.frames==1 && isequal(d.image_size(:)',[1920 1080]));
check('observation serial disabled',strcmp(d.serial,'DISABLED') && ~d.motion_allowed);
check('engraved ruler marks ordered',all(diff(truth)>0) && all(diff(points(:,2))>0));
check('only unclipped ticks used; at least10 marks and200mm span', ...
 sum(accepted)>=10 && max(truth)-min(truth)>=200);
check('seven fixed features agree on1px right shift',numel(d.fixed_surface_patches)==7 && ...
 all(arrayfun(@(p)p.correlation>.9 && isequal(p.integer_shift_px(:)',[1 0]),d.fixed_surface_patches)));
ij=nchoosek(1:numel(truth),2);expected=truth(ij(:,2))-truth(ij(:,1));
items=cell(1,3);
for k=1:3
 H=models.models(k).H_image_to_paper_plane;
 projected=project(H,points);
 measured=vecnorm(projected(ij(:,2),:)-projected(ij(:,1),:),2,2);errors=measured-expected;
 % Report all pairs, dependent observations, not independent repeated trials.
 [maxError,worst]=max(abs(errors));
 pc=project(H,d.current_corners_ABCD_px);paperSides=vecnorm(pc([2 3 4 1],:)-pc,2,2);
 % Explicit200mm interval3cm->23cm; shadowed24/25cm remain rejected.
 a=find(truth==30);b=find(truth==230);length200=norm(projected(b,:)-projected(a,:));
 items{k}=struct('model',models.models(k).model,'H_image_to_old_paper_plane',H, ...
  'ruler_used_to_fit_this_model',false,'pair_count',size(ij,1), ...
  'pair_expected_mm',expected','pair_measured_mm',measured','pair_error_mm',errors', ...
  'pair_rms_error_mm',sqrt(mean(errors.^2)),'pair_max_abs_error_mm',maxError, ...
  'worst_tick_labels_cm',truth(ij(worst,:))'/10, ...
  'span_200mm_measured_mm',length200,'span_200mm_error_mm',length200-200, ...
  'new_paper_edge_lengths_mm',paperSides', ...
  'ruler_strip_engineering_limit_mm',3,'ruler_strip_within3mm',maxError<=3, ...
  'declared_tick2px_endpoint_length_bound_mm',4*norm(project(H,[822 501])-project(H,[822 500])));
 fprintf('%s:200mm->%.3fmm; all%d ruler pairs max error%.3fmm; strip3mm criterion%d\n', ...
  items{k}.model,length200,size(ij,1),maxError,items{k}.ruler_strip_within3mm);
end
check('simple model meets declared3mm ruler strip diagnostic',items{1}.ruler_strip_within3mm);
report=struct('engine','local MATLAB','release',version('-release'),'models',[items{:}], ...
 'image_sha256',d.image_sha256,'paper_has_moved',true,'fixed_scene_integer_translation_px',[1 0], ...
 'accepted_tick_labels_cm',truth'/10,'rejected_boundary_tick_labels_cm',allTruth(~accepted)'/10, ...
 'span_200mm_endpoint_labels_cm',[3 23], ...
 'engineering_strip_criterion_mm',3,'criterion_is_not_official_rule',true, ...
 'criterion_scope','single ruler strip; pairs share endpoints; surface thickness and x-axis not independently validated', ...
 'ruler_surface_height_above_disk_mm',[],'perpendicular_axis_ruler_checked',false, ...
 'ruler_nominal_interval_range_mm',[min(expected) max(expected)], ...
 'check_count',numel(checks),'failure_count',sum(~[checks.passed]),'checks',checks,'passed',all([checks.passed]), ...
 'suggested_low_complexity_model','similarity', ...
 'full_plane_accuracy_accepted',false,'plane_to_chassis_verified',false, ...
 'desired_parking_reference_verified',false,'sensor_exposure_age_verified',false,'motion_allowed',false);
f=fopen(fullfile(out,'matlab-result.json'),'w','n','UTF-8');assert(f~=-1);fprintf(f,'%s\n',jsonencode(report));fclose(f);
fprintf('RULER MATLAB%d checks/%d failures; motion_allowed0.\n',report.check_count,report.failure_count);
assert(report.passed);
 function check(name,passed)
  checks(end+1)=struct('name',name,'passed',logical(passed));
 end
end
function p=project(H,p)
p=[p ones(size(p,1),1)]*H';p=p(:,1:2)./p(:,3);
end
