function check_hover_wait_20261113
% Conditional geometry using the retained measured lift calibration.
root=fileparts(fileparts(mfilename('fullpath')));
out=fullfile(root,'evidence','integration','2026-11-13','source-auto-index-observe-20261113-a');
top_bottom_mm=119;material_top_mm=60;wait_clearance_mm=20;
scale=1600;pick=118800;safe_return=7200;
wait_height=material_top_mm+wait_clearance_mm;
wait_pulses=(top_bottom_mm-wait_height)*scale;
assert(wait_pulses>safe_return && wait_pulses<pick);
pickup_height=top_bottom_mm-pick/scale;
strict_clear_depth=pick-65*scale;
assert(safe_return<strict_clear_depth && strict_clear_depth>0);
remaining_descent=(pick-wait_pulses)/scale;
speed=1846.4*3200/60/scale;
ideal=(remaining_descent+65)/speed;
r=struct('passed',true,'engine','local MATLAB','retained_top_bottom_mm',top_bottom_mm, ...
 'user_material_height_mm',material_top_mm,'user_confirmed_wait_clearance_mm',wait_clearance_mm, ...
 'nominal_wait_bottom_mm',wait_height,'wait_depth_virtual_pulses',wait_pulses, ...
 'pickup_depth_virtual_pulses',pick,'remaining_descent_mm',remaining_descent, ...
 'pickup_bottom_mm',pickup_height,'strict_65mm_clear_when_depth_less_than_pulses',strict_clear_depth, ...
 'safe_return_depth_virtual_pulses',safe_return, ...
 'ideal_short_descent_plus_65mm_rise_s',ideal, ...
 'actual_height_remeasurement_performed',false,'camera_moves_with_lift',true, ...
 'old_image_mapping_invalid_at_wait_height',true,'new_capture_required',true, ...
 'not_actual_clearance_or_timing_validation',true,'pick_allowed',false);
f=fopen(fullfile(out,'matlab-hover-wait.json'),'w','n','UTF-8');fprintf(f,'%s\n',jsonencode(r));fclose(f);
fprintf('Conditional hover depth %.0fp, nominal bottom%.1fmm; remaining descent%.2fmm; ideal descent+65mm rise%.3fs\n', ...
 wait_pulses,wait_height,remaining_descent,ideal);
end
