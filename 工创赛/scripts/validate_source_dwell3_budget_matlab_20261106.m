function validate_source_dwell3_budget_matlab_20261106
% Timing feasibility model only. Linear partial-travel scaling is an estimate;
% full empty-lift measured times do not prove loaded time or hover clearance.
root=fileparts(fileparts(mfilename('fullpath')));
out=fullfile(root,'evidence','integration','2026-11-06','source-vision-new-pose','dwell3-budget');
if ~exist(out,'dir'),mkdir(out);end
lift=jsondecode(fileread(fullfile(root,'evidence','integration','2026-11-06','lift-retarget','round-trip-result.json')));
down=lift.down_move_command_to_stable_ms/1000;up=lift.up_move_command_to_stable_ms/1000;
dwell=3;top=119;grasp=50;height=60;travel=top-grasp;
% A cylinder gripped with claw bottom at50 still extends50mm below claw.
% After lifting d mm, held cylinder base is at d mm above source surface.
clearance_lift=height;estimated_up=up*clearance_lift/travel;
hover=[70,75,80,90,100,119];estimated_down=down*(hover-grasp)/travel;
overhead=[0,.2,.4,.6];budget=estimated_down'+estimated_up+overhead;
report=struct('engine','local MATLAB','release',version('-release'),'user_reported_dwell_s',dwell, ...
 'historical_measured_empty_down_s',down,'historical_measured_empty_full_up_s',up, ...
 'measured_full_down_plus_full_up_s',down+up,'full_lift_cycle_exceeds_dwell_without_overhead',down+up>dwell, ...
 'retained_top_claw_bottom_mm',top,'selected_grasp_claw_bottom_mm',grasp,'retained_material_height_mm',height, ...
 'required_held_material_base_height_mm',height,'minimum_upward_lift_to_equal_other_material_top_mm',clearance_lift, ...
 'partial_up_s_linear_estimate_not_measurement',estimated_up,'top_start_pick_clear_s_without_overhead_estimate',down+estimated_up, ...
 'hover_claw_bottom_candidates_mm',hover,'combined_detection_alignment_close_and_dispatch_overhead_s',overhead, ...
 'estimated_pick_clear_seconds_by_hover_rows_overhead_columns',budget,'nominal_less_than3s',budget<dwell, ...
 'hover_clearance_or_collision_physically_accepted',false,'loaded_motion_accepted',false,'timing_success_accepted',false, ...
 'declared_partial_motion_model','linear distance scaling of historical empty-lift command-to-stable duration; acceleration, load, feedback settling and overlap unmodelled', ...
 'decision','full-height sequential approach lacks3s budget; evaluate raised hover before stop, without moving hardware yet', ...
 'checks_passed',all([down+up>dwell,estimated_up>0,all(hover>height),all(diff(estimated_down)>0),all(diff(budget,1,2)>0)]), ...
 'motion_allowed',false,'actuator_commands',0);
fid=fopen(fullfile(out,'matlab-result.json'),'w','n','UTF-8');assert(fid~=-1);fprintf(fid,'%s',jsonencode(report));fclose(fid);save(fullfile(out,'matlab-result.mat'),'report');
fprintf('DWELL3 MATLAB full empty up+down%.3fs; pick-clear partial estimate fromtop%.3fs before overhead; hover75/80 with0.4soverhead%.3f/%.3fs, diagnostic only\n', ...
 down+up,down+estimated_up,budget(2,3),budget(3,3));assert(report.checks_passed);
end
