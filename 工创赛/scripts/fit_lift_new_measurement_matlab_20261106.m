function fit_lift_new_measurement_matlab_20261106
% Fit only current measured samples; no legacy taught heights or coarse scale.
root=fileparts(fileparts(mfilename('fullpath')));
p=fullfile(root,'calibration','lift_new_measurements_20261106.json');
d=jsondecode(fileread(p));s=d.samples;assert(numel(s)==1);
drop=s.reading_before_mm-s.reading_after_mm;
assert(drop>0 && s.command_virtual_pulses==5000 && s.controller_state==4 && s.controller_cause==0);
scale=10;if bitand(s.options_raw,128),scale=100;end
raw_delta=s.position_after_raw-s.position_before_raw;
cmd_raw=s.command_virtual_pulses*360*scale/3200;
enc_mod=mod(s.encoder_after-s.encoder_before,65536);
expected_enc_mod=mod(s.command_virtual_pulses/3200*65536,65536);
enc_error=mod(enc_mod-expected_enc_mod+32768,65536)-32768;
ppmm=s.command_virtual_pulses/drop;
requested_drop=119-50;nominal_pulses=requested_drop*ppmm;
% Declared ruler perturbation, not a measured error or acceptance guarantee.
declared_drop=drop+[-.5,0,.5];ratio=s.command_virtual_pulses./declared_drop;
checks=[drop==3,scale==100,cmd_raw==56250, ...
 abs(s.target_raw-s.position_before_raw-cmd_raw)<=scale, ...
 abs(raw_delta-cmd_raw)<=.3*scale,abs(enc_error)<=365, ...
 abs(ppmm*drop-s.command_virtual_pulses)<1e-8, ...
 abs(nominal_pulses-115000)<1e-8,nominal_pulses>105000];
report=struct('engine','local MATLAB','version',version,'release',version('-release'), ...
 'sample_count',1,'measured_drop_mm',drop,'virtual_pulses_per_mm_candidate',ppmm, ...
 'mm_per_virtual_pulse_candidate',1/ppmm,'raw_feedback_units_per_deg',scale, ...
 'command_angle_deg',cmd_raw/scale,'feedback_angle_delta_deg',raw_delta/scale, ...
 'target_error_deg',(raw_delta-cmd_raw)/scale,'encoder_modular_residual_counts',enc_error, ...
 'declared_drop_mm_sensitivity',declared_drop,'declared_pulses_per_mm_sensitivity',ratio, ...
 'declared_sensitivity_is_measured_error_bound',false, ...
 'requested_grasp_bottom_mm',50,'nominal_total_drop_mm',requested_drop, ...
 'nominal_total_pulses_candidate_only',nominal_pulses,'existing_source_limit_pulses',105000, ...
 'exceeds_existing_source_limit',true,'verified_physical_travel_mm',drop, ...
 'checks',checks,'check_count',numel(checks),'failure_count',sum(~checks), ...
 'passed',all(checks),'full_travel_calibration_passed',false,'motion_allowed',false);
out=fullfile(root,'evidence','integration','2026-11-06','lift-new-calibration','first-step');
fid=fopen(fullfile(out,'matlab-fit.json'),'w','n','UTF-8');assert(fid~=-1);
c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(report));
save(fullfile(out,'matlab-fit.mat'),'report');
fprintf('NEW LIFT: %.3fmm /5000p => %.6f p/mm; checks=%d failures=%d; 69mm nominal %.0fp exceeds existing105000, no motion release\n',drop,ppmm,numel(checks),sum(~checks),nominal_pulses);
assert(report.passed);
end
