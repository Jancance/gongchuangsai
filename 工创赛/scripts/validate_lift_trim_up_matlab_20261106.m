function validate_lift_trim_up_matlab_20261106
root=fileparts(fileparts(mfilename('fullpath')));
out=fullfile(root,'evidence','integration','2026-11-06','lift-trim-up');if ~exist(out,'dir'),mkdir(out);end
pulses=2400;ratios=[1600,110800/(119-48.5),10000/6];drop=pulses./ratios;end_h=48.5+drop;
angle=pulses*360/3200;a=60*6;v=30*6;ta=v/a;T=angle/v+ta;
checks=[pulses>0 && pulses<=4000,all(end_h>=49.9 & end_h<=50.1), ...
 abs(T-2)<1e-8,all(drop>0),48.5+4000/min(ratios)<119, ...
 2400*360*100/3200==27000,mod(-pulses/3200*65536,65536)==16384];
report=struct('engine','local MATLAB','version',version,'release',version('-release'), ...
 'initial_height_user_mm',48.5,'trim_up_virtual_pulses',pulses,'maximum_trim_up_pulses',4000, ...
 'rpm',30,'acceleration_rpm_s',60,'nominal_duration_s',T,'declared_ratios',ratios, ...
 'nominal_end_heights_mm',end_h,'checks',checks,'check_count',numel(checks),'failure_count',sum(~checks), ...
 'passed',all(checks),'VM_remains_requested_during_trim',true,'reset_or_flash_executed',false, ...
 'home_or_full_return_allowed_by_trim',false,'reference_or_health_fabricated',false, ...
 'hardware_operated',false,'endpoint_physical_accepted',false);
fid=fopen(fullfile(out,'matlab-result.json'),'w','n','UTF-8');assert(fid~=-1);c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(report));save(fullfile(out,'matlab-result.mat'),'report');
fprintf('MATLAB TRIM: upward2400p %.2fs, endpoints %.2f..%.2fmm checks%d failures%d\n',T,min(end_h),max(end_h),numel(checks),report.failure_count);
assert(report.passed);
end
