function validate_source_carrier_height_matlab_20261106
% New user measurements; evaluate both possible height references without
% selecting one or converting an ambiguous reference into a motor target.
root=fileparts(fileparts(mfilename('fullpath')));
out=fullfile(root,'evidence','integration','2026-11-06','source-parallel-plan');
deck=54.23;lip=69.23;wall=15;clearance=5;transfer=74.23;release=60;
top=119;grasp=50;offset=grasp;
required_claw_transfer=transfer+offset;required_claw_release=release+offset;
checks=[abs(lip-deck-wall)<1e-9,abs(transfer-lip-clearance)<1e-9, ...
 abs(release-deck-5.77)<1e-9,required_claw_transfer>top,required_claw_release<=top];
report=struct('engine','local MATLAB','release',version('-release'),'user_measured_carrier_deck_relative_source_mm',deck, ...
 'user_measured_carrier_highest_relative_source_mm',lip,'user_measured_lip_above_deck_mm',wall, ...
 'user_requested_transfer_height_mm',transfer,'user_requested_release_height_mm',release, ...
 'requested_height_reference_confirmed',true,'clearance_mm',clearance,'drop_to_support_if_material_bottom60_mm',release-deck, ...
 'retained_source_grasp_claw_bottom_mm',grasp,'retained_top_claw_bottom_mm',top, ...
 'if_material_bottom_reference_required_claw_transfer_mm',required_claw_transfer, ...
 'if_material_bottom_reference_required_claw_release_mm',required_claw_release, ...
 'extra_claw_height_beyond_top_mm',required_claw_transfer-top, ...
 'if_claw_bottom_reference_material_bottom_transfer_mm',transfer-offset, ...
 'if_claw_bottom_reference_material_bottom_release_mm',release-offset, ...
 'release_claw_is_already_above_lip_if_material_bottom60',required_claw_release>lip+clearance, ...
 'possible_source_grasp_claw_height_to_fit_current_top_mm',top-transfer, ...
 'possible_lower_grasp_position_is_mechanically_verified',false,'new_pulses_computed',false, ...
 'checks_passed',all(checks),'check_count',numel(checks),'motion_allowed',false);
fid=fopen(fullfile(out,'carrier-height-matlab.json'),'w','n','UTF-8');assert(fid~=-1);fprintf(fid,'%s',jsonencode(report));fclose(fid);
fprintf('CARRIER MATLAB checks%d passed%d: material-base74.23 needs claw124.23, retained top119 short%.2fmm; no ambiguous target/pulse emitted\n',numel(checks),report.checks_passed,required_claw_transfer-top);assert(report.checks_passed);
end
