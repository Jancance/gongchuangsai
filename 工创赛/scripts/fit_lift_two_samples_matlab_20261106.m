function fit_lift_two_samples_matlab_20261106
% Current ruler samples only. Fit does not release the untested 69mm travel.
root=fileparts(fileparts(mfilename('fullpath')));
d=jsondecode(fileread(fullfile(root,'calibration','lift_new_measurements_20261106.json')));
s=d.samples;assert(numel(s)==2);
p=[s.command_virtual_pulses];h0=[s.reading_before_mm];h1=[s.reading_after_mm];drop=h0-h1;
scale=10+90*(bitand([s.options_raw],128)~=0);
target=[s.target_raw]-[s.position_before_raw];feedback=[s.position_after_raw]-[s.position_before_raw];
expected=p.*360.*scale/3200;
enc_delta=mod([s.encoder_after]-[s.encoder_before],65536);
enc_expected=mod(p/3200*65536,65536);
enc_error=mod(enc_delta-enc_expected+32768,65536)-32768;
ratio=p./drop;combined=sum(p)/sum(drop);
between_encoder=mod(s(2).encoder_before-s(1).encoder_after+32768,65536)-32768;
desired_total_drop=119-50;desired_total_p=desired_total_drop*combined;
remaining_drop=113-50;remaining_p=remaining_drop*combined;
% +/-0.5mm on the two endpoints is an illustrative, unmeasured error budget.
declared_endpoint_error=[-.5,0,.5];candidates=[];
for a=declared_endpoint_error
 for b=declared_endpoint_error
  candidates(end+1)=sum(p)/(h0(1)+a-h1(end)-b); %#ok<AGROW>
 end
end
checks=[all(drop>0),all(p==5000),h0(2)==h1(1), ...
 all([s.controller_state]==4),all([s.controller_cause]==0),all(scale==100), ...
 all(abs(target-expected)<=scale),all(abs(feedback-expected)<=.3*scale), ...
 all(abs(enc_error)<=365),abs(between_encoder)<=365, ...
 max(ratio)-min(ratio)<1e-8,sum(p)==10000,sum(drop)==6, ...
 abs(combined-10000/6)<1e-8,desired_total_p>105000, ...
 abs(remaining_p+sum(p)-desired_total_p)<1e-8];
report=struct('engine','local MATLAB','version',version,'release',version('-release'), ...
 'sample_count',2,'per_sample_measured_drop_mm',drop,'total_measured_drop_mm',sum(drop), ...
 'total_virtual_pulses',sum(p),'per_sample_virtual_pulses_per_mm',ratio, ...
 'combined_virtual_pulses_per_mm_candidate',combined,'combined_mm_per_virtual_pulse',1/combined, ...
 'feedback_error_deg',(feedback-expected)./scale,'encoder_modular_residual_counts',enc_error, ...
 'between_reset_encoder_delta_counts',between_encoder, ...
 'declared_endpoint_error_mm',declared_endpoint_error,'declared_ratio_range',[min(candidates),max(candidates)], ...
 'declared_error_budget_is_measured',false,'initial_height_mm',119,'current_height_mm',113, ...
 'grasp_bottom_candidate_mm',50,'nominal_total_pulses_candidate_only',desired_total_p, ...
 'nominal_remaining_pulses_candidate_only',remaining_p,'existing_source_limit_pulses',105000, ...
 'exceeds_existing_source_limit',true,'checks',checks,'check_count',numel(checks), ...
 'failure_count',sum(~checks),'passed',all(checks), ...
 'short_stroke_calibration_consistent',all(checks), ...
 'full_travel_accuracy_accepted',false,'loaded_motion_accepted',false,'long_motion_allowed',false);
out=fullfile(root,'evidence','integration','2026-11-06','lift-new-calibration');
fid=fopen(fullfile(out,'matlab-two-samples.json'),'w','n','UTF-8');assert(fid~=-1);
c=onCleanup(@()fclose(fid)); %#ok<NASGU>
fprintf(fid,'%s',jsonencode(report));save(fullfile(out,'matlab-two-samples.mat'),'report');
fprintf('NEW LIFT two samples: total%.1fmm/%dp => %.6fp/mm; checks=%d failures=%d; current113mm; no long motion release\n',sum(drop),sum(p),combined,numel(checks),sum(~checks));
assert(report.passed);
end
