function check_auto_index_pick_budget_20261113
% Minimum necessary time budget; measured command phases are not clearance evidence.
root=fileparts(fileparts(mfilename('fullpath')));
out=fullfile(root,'evidence','integration','2026-11-13','source-auto-index-observe-20261113-a');
d=jsondecode(fileread(fullfile(root,'evidence','integration','2026-11-13','near-pzq', ...
 'near-pzq-slot3-20261113-165938.json')));assert(d.complete);
c=jsondecode(fileread(fullfile(out,'matlab-cadence-result.json')));assert(c.passed);
trace=d.trace;phase=[trace.g_it_auto_phase];elapsed=[trace.g_it_auto_elapsed_ms];
begin=find(phase==2,1);grip=find(phase==3,1);assert(~isempty(begin) && ~isempty(grip));
% Retained actual lift calibration: 1600 virtual pulses/mm; profile1846.4rpm.
% 3200 virtual pulses/rev from the actual degree/pulse conversion.
pulses_per_mm=1600;rpm=1846.4;speed_mm_s=rpm*3200/60/pulses_per_mm;
clearance_mm=65;minimum_rise_s=clearance_mm/speed_mm_s;
descent_to_grip_s=(elapsed(grip)-elapsed(begin))/1000;
from_trigger_to_grip_s=elapsed(grip)/1000;
minimum_total_s=from_trigger_to_grip_s+minimum_rise_s;
windows=c.complete_gate_windows_at_least_150ms;
% First interval may start before capture. Exclude it from full-dwell estimates.
steady=windows(2:end,3);assert(numel(steady)>5);
r=struct('passed',true,'engine','local MATLAB','user_clearance_strictly_greater_than_mm',65, ...
 'virtual_pulses_per_mm',pulses_per_mm,'profile_rpm',rpm,'ideal_speed_mm_s',speed_mm_s, ...
 'measured_trigger_to_return_phase_s',from_trigger_to_grip_s, ...
 'measured_descent_phase_s',descent_to_grip_s, ...
 'ideal_65mm_rise_without_accel_or_bus_s',minimum_rise_s, ...
 'optimistic_trigger_to_65mm_lower_estimate_s',minimum_total_s, ...
 'full_observed_gate_min_median_max_s',[min(steady),median(steady),max(steady)], ...
 'optimistic_margin_against_min_gate_s',min(steady)-minimum_total_s, ...
 'first_gate_may_be_capture_truncated',true, ...
 'actual_grip_evidence_available',false,'actual_65mm_crossing_time_available',false, ...
 'excludes_rise_acceleration_and_command_latency',true,'excludes_side_yaw_and_extension',true, ...
 'not_a_proof_of_safe_window',true,'automatic_pick_ready',false,'motion_allowed',false);
f=fopen(fullfile(out,'matlab-pick-budget.json'),'w','n','UTF-8');fprintf(f,'%s\n',jsonencode(r));fclose(f);
fprintf('Observed return phase %.3fs; ideal65mm rise %.3fs; optimistic total %.3fs\n',from_trigger_to_grip_s,minimum_rise_s,minimum_total_s);
fprintf('Full vision gates min/median/max %.3f %.3f %.3fs; optimistic margin %.3fs BEFORE rise overhead\n', ...
 r.full_observed_gate_min_median_max_s,r.optimistic_margin_against_min_gate_s);
end
